export function getTemplateBySlug(slug: string): TemplateItem | undefined {
  return templates.find((t) => t.slug.toLowerCase() === slug.toLowerCase());
}

export function getTemplatesByCategory(categorySlug: string): TemplateItem[] {
  return templates.filter((t) => t.category.toLowerCase() === categorySlug.toLowerCase());
}

export function getFeaturedTemplates(): TemplateItem[] {
  return templates.filter((t) => t.featured);
}
